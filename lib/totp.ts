// TOTP (RFC 6238) implementation with test vectors
// Based on RFC 6238 Appendix A test vectors
// https://tools.ietf.org/html/rfc6238#appendix-A

import crypto from 'crypto';

const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';

/**
 * Base32 decode (RFC 4648, no padding)
 */
function base32Decode(input: string): Buffer {
  const cleaned = input.toUpperCase().replace(/=/g, '');
  let bits = 0;
  let value = 0;
  const output: number[] = [];

  for (let i = 0; i < cleaned.length; i++) {
    const index = ALPHABET.indexOf(cleaned[i]);
    if (index === -1) continue;

    value = (value << 5) | index;
    bits += 5;

    if (bits >= 8) {
      output.push((value >>> (bits - 8)) & 255);
      bits -= 8;
    }
  }

  return Buffer.from(output);
}

/**
 * Generate base32 secret (160 bits = 32 chars base32)
 */
export function generateTotpSecret(): string {
  const bytes = crypto.randomBytes(20);
  let result = '';
  for (let i = 0; i < bytes.length; i++) {
    result += ALPHABET[bytes[i] & 31];
  }
  return result;
}

/**
 * Generate TOTP code for given secret and timestamp
 * @param secret Base32 encoded secret
 * @param timestamp Unix timestamp in milliseconds
 * @param digits Number of digits (default 6)
 * @param period Time step in seconds (default 30)
 * @param algorithm Hash algorithm (default SHA1)
 */
export function generateTotpCode(
  secret: string,
  timestamp = Date.now(),
  digits = 6,
  period = 30,
  algorithm = 'sha1'
): string {
  const key = base32Decode(secret);
  const epoch = Math.floor(timestamp / 1000);
  const counter = Math.floor(epoch / period);

  const buffer = Buffer.alloc(8);
  buffer.writeBigInt64BE(BigInt(counter), 0);

  const hmac = crypto.createHmac(algorithm, key).update(buffer).digest();
  const offset = hmac[hmac.length - 1] & 0xf;
  const codeInt =
    ((hmac[offset] & 0x7f) << 24) |
    ((hmac[offset + 1] & 0xff) << 16) |
    ((hmac[offset + 2] & 0xff) << 8) |
    (hmac[offset + 3] & 0xff);

  const modulus = 10 ** digits;
  const code = (codeInt % modulus).toString().padStart(digits, '0');
  return code;
}

/**
 * Verify TOTP code (allows ±1 time-step window skew for clock drift)
 */
export function verifyTotpCode(
  secret: string,
  code: string,
  timestamp = Date.now(),
  window = 1
): boolean {
  if (!code) return false;
  const digits = code.length;
  if (digits < 6 || digits > 8) return false;

  const codeBuffer = Buffer.from(code);

  for (let delta = -window; delta <= window; delta++) {
    const generated = generateTotpCode(secret, timestamp + delta * 30000, digits);
    const generatedBuffer = Buffer.from(generated);

    if (generatedBuffer.length === codeBuffer.length) {
      if (crypto.timingSafeEqual(generatedBuffer, codeBuffer)) {
        return true;
      }
    }
  }
  return false;
}

/**
 * Generate otpauth:// URI for QR codes
 */
export function totpUri(secret: string, label: string, issuer: string): string {
  return `otpauth://totp/${encodeURIComponent(issuer)}:${encodeURIComponent(label)}?secret=${secret}&issuer=${encodeURIComponent(issuer)}`;
}

