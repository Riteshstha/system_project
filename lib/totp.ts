/**
 * Run RFC 6238 test vectors - call this in tests
 * Uses raw secret directly (not base32-decoded) to match RFC test format
 */
export function runRfc6238TestVectors(): { passed: number; failed: number; details: any[] } {
  let passed = 0;
  let failed = 0;
  const details: any[] = [];

  for (const vector of RFC6238_TEST_VECTORS) {
    // For RFC test vectors, use the raw secret directly
    const key = Buffer.from(vector.secret);
    const epoch = Math.floor(vector.timestamp / 1000);
    const period = 30;
    const counter = Math.floor(epoch / period);

    const buffer = Buffer.alloc(8);
    buffer.writeBigInt64BE(BigInt(counter), 0);

    const hmac = crypto.createHmac(vector.algorithm, key).update(buffer).digest();
    const offset = hmac[hmac.length - 1] & 0xf;
    const codeInt =
      ((hmac[offset] & 0x7f) << 24) |
      ((hmac[offset + 1] & 0xff) << 16) |
      ((hmac[offset + 2] & 0xff) << 8) |
      (hmac[offset + 3] & 0xff);

    const modulus = 10 ** vector.digits;
    const generated = (codeInt % modulus).toString().padStart(vector.digits, '0');

    const ok = generated === vector.expected;
    if (ok) passed++;
    else failed++;

    details.push({
      name: vector.name,
      expected: vector.expected,
      generated,
      passed: ok,
    });
  }

  return { passed, failed, details };
}